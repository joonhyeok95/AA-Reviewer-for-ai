-- =====================================================================
-- 02. 공지사항 / 메일 템플릿  (Oracle)
--  - 다국어 : 작성자가 언어를 선택해 입력 (TB_NOTICE_I18N, 언어 = 공통코드 LANG)
--  - 대표 언어(BASE_LANG_CD) : 조회/메일 시 사용자 언어 버전이 없으면 대표 언어 버전으로 대체
--  - 사업장/부서는 코드만 저장 (명칭은 인사 마스터 TB_WORKPLACE / TB_DEPT 에서 조회 시점에)
-- =====================================================================
CREATE SEQUENCE SQ_NOTICE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SQ_NOTICE_FILE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SQ_NOTICE_MAIL_HIST START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_NOTICE (
    NOTICE_ID           NUMBER(19)      NOT NULL,
    CATEGORY_CD         VARCHAR2(50)    NOT NULL,
    TAG_CD              VARCHAR2(50),
    BASE_LANG_CD        VARCHAR2(10)    NOT NULL,
    POST_DATE           TIMESTAMP(6)    NOT NULL,
    POPUP_YN            VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    POPUP_START_DT      DATE,
    POPUP_END_DT        DATE,
    MAIL_SEND_TYPE_CD   VARCHAR2(50)    DEFAULT 'NONE' NOT NULL,
    MAIL_STATUS_CD      VARCHAR2(20)    DEFAULT 'NONE' NOT NULL,
    MAIL_SEND_DT        TIMESTAMP(6),
    VIEW_CNT            NUMBER(10)      DEFAULT 0   NOT NULL,
    DEL_YN              VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    CREATED_BY          VARCHAR2(50)    NOT NULL,
    CREATED_AT          TIMESTAMP(6)    NOT NULL,
    UPDATED_BY          VARCHAR2(50)    NOT NULL,
    UPDATED_AT          TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_NOTICE PRIMARY KEY (NOTICE_ID)
);
COMMENT ON TABLE  TB_NOTICE                   IS '공지사항';
COMMENT ON COLUMN TB_NOTICE.NOTICE_ID         IS '공지ID (SQ_NOTICE)';
COMMENT ON COLUMN TB_NOTICE.CATEGORY_CD       IS '분류 (공통코드 NOTICE_CATEGORY)';
COMMENT ON COLUMN TB_NOTICE.TAG_CD            IS '태그 (공통코드 NOTICE_TAG)';
COMMENT ON COLUMN TB_NOTICE.BASE_LANG_CD      IS '대표 언어 (공통코드 LANG). 기본값 = 처음 입력한 언어';
COMMENT ON COLUMN TB_NOTICE.POST_DATE         IS '게시일시 (미래면 예약 게시 - 일반 사용자 목록에 노출되지 않음)';
COMMENT ON COLUMN TB_NOTICE.POPUP_YN          IS '팝업여부';
COMMENT ON COLUMN TB_NOTICE.POPUP_START_DT    IS '팝업 시작일';
COMMENT ON COLUMN TB_NOTICE.POPUP_END_DT      IS '팝업 종료일';
COMMENT ON COLUMN TB_NOTICE.MAIL_SEND_TYPE_CD IS '메일 발송 유형 (공통코드 MAIL_SEND_TYPE: NONE, TARGET)';
COMMENT ON COLUMN TB_NOTICE.MAIL_STATUS_CD    IS '메일 발송 상태 (NONE: 미발송, READY: 게시일시 도래 시 발송, SENDING, DONE, FAIL)';
COMMENT ON COLUMN TB_NOTICE.MAIL_SEND_DT      IS '메일 발송 완료일시';
COMMENT ON COLUMN TB_NOTICE.VIEW_CNT          IS '조회수 (사용자·일자별 1회 - TB_NOTICE_VIEW_LOG)';
COMMENT ON COLUMN TB_NOTICE.DEL_YN            IS '삭제여부 (논리 삭제)';
CREATE INDEX IX_NOTICE_01 ON TB_NOTICE (DEL_YN, POST_DATE);
CREATE INDEX IX_NOTICE_02 ON TB_NOTICE (MAIL_STATUS_CD, POST_DATE);

CREATE TABLE TB_NOTICE_I18N (
    NOTICE_ID       NUMBER(19)      NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    TITLE           VARCHAR2(500)   NOT NULL,
    CONTENT_HTML    CLOB            NOT NULL,
    CONTENT_TEXT    CLOB,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_NOTICE_I18N PRIMARY KEY (NOTICE_ID, LANG_CD),
    CONSTRAINT FK_NOTICE_I18N_01 FOREIGN KEY (NOTICE_ID) REFERENCES TB_NOTICE (NOTICE_ID)
);
COMMENT ON TABLE  TB_NOTICE_I18N              IS '공지사항 언어별 내용 (작성한 언어만 존재)';
COMMENT ON COLUMN TB_NOTICE_I18N.LANG_CD      IS '언어 (공통코드 LANG)';
COMMENT ON COLUMN TB_NOTICE_I18N.TITLE        IS '제목';
COMMENT ON COLUMN TB_NOTICE_I18N.CONTENT_HTML IS '본문 HTML (저장 시 XSS 정화)';
COMMENT ON COLUMN TB_NOTICE_I18N.CONTENT_TEXT IS '본문 텍스트 (태그 제거, 검색용)';

CREATE TABLE TB_NOTICE_FILE (
    FILE_ID         NUMBER(19)      NOT NULL,
    NOTICE_ID       NUMBER(19)      NOT NULL,
    ORG_FILE_NM     VARCHAR2(500)   NOT NULL,
    SAVE_PATH       VARCHAR2(1000)  NOT NULL,
    FILE_SIZE       NUMBER(19)      NOT NULL,
    FILE_EXT        VARCHAR2(20)    NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_NOTICE_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_NOTICE_FILE_01 FOREIGN KEY (NOTICE_ID) REFERENCES TB_NOTICE (NOTICE_ID)
);
COMMENT ON TABLE  TB_NOTICE_FILE              IS '공지사항 첨부파일 (게시물 공통 - 언어별 분리 안 함)';
COMMENT ON COLUMN TB_NOTICE_FILE.FILE_ID      IS '파일ID (SQ_NOTICE_FILE)';
COMMENT ON COLUMN TB_NOTICE_FILE.ORG_FILE_NM  IS '원본 파일명';
COMMENT ON COLUMN TB_NOTICE_FILE.SAVE_PATH    IS '저장 경로 (저장소 기준 상대경로, 임의 파일명)';
COMMENT ON COLUMN TB_NOTICE_FILE.FILE_SIZE    IS '파일 크기 (byte)';
COMMENT ON COLUMN TB_NOTICE_FILE.FILE_EXT     IS '확장자 (소문자)';
CREATE INDEX IX_NOTICE_FILE_01 ON TB_NOTICE_FILE (NOTICE_ID);

CREATE TABLE TB_NOTICE_MAIL_TARGET (
    NOTICE_ID       NUMBER(19)      NOT NULL,
    TARGET_TYPE     VARCHAR2(20)    NOT NULL,
    TARGET_CD       VARCHAR2(50)    NOT NULL,
    INCLUDE_SUB_YN  VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_NOTICE_MAIL_TARGET PRIMARY KEY (NOTICE_ID, TARGET_TYPE, TARGET_CD),
    CONSTRAINT FK_NOTICE_MAIL_TARGET_01 FOREIGN KEY (NOTICE_ID) REFERENCES TB_NOTICE (NOTICE_ID)
);
COMMENT ON TABLE  TB_NOTICE_MAIL_TARGET                IS '공지 메일 대상 (발송 시점에 인사 마스터 기준으로 수신자 추출)';
COMMENT ON COLUMN TB_NOTICE_MAIL_TARGET.TARGET_TYPE    IS '대상 유형 (공통코드 MAIL_TARGET_TYPE: WORKPLACE, DEPT)';
COMMENT ON COLUMN TB_NOTICE_MAIL_TARGET.TARGET_CD      IS '사업장코드 또는 부서코드 (인사 마스터)';
COMMENT ON COLUMN TB_NOTICE_MAIL_TARGET.INCLUDE_SUB_YN IS '하위부서 포함여부 (DEPT 만 해당)';

CREATE TABLE TB_NOTICE_MAIL_HIST (
    HIST_ID         NUMBER(19)      NOT NULL,
    NOTICE_ID       NUMBER(19)      NOT NULL,
    RECEIVER_ID     VARCHAR2(50)    NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    SEND_DT         TIMESTAMP(6)    NOT NULL,
    STATUS_CD       VARCHAR2(20)    NOT NULL,
    ERROR_MSG       VARCHAR2(1000),
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_NOTICE_MAIL_HIST PRIMARY KEY (HIST_ID)
);
COMMENT ON TABLE  TB_NOTICE_MAIL_HIST             IS '공지 메일 발송 이력 (수신자별)';
COMMENT ON COLUMN TB_NOTICE_MAIL_HIST.RECEIVER_ID IS '수신자 사용자ID';
COMMENT ON COLUMN TB_NOTICE_MAIL_HIST.LANG_CD     IS '발송 언어 (수신자 설정 언어)';
COMMENT ON COLUMN TB_NOTICE_MAIL_HIST.STATUS_CD   IS '발송 결과 (공통코드 MAIL_STATUS: SUCCESS, FAIL)';
COMMENT ON COLUMN TB_NOTICE_MAIL_HIST.ERROR_MSG   IS '실패 사유';
CREATE INDEX IX_NOTICE_MAIL_HIST_01 ON TB_NOTICE_MAIL_HIST (NOTICE_ID);

CREATE TABLE TB_NOTICE_VIEW_LOG (
    NOTICE_ID       NUMBER(19)      NOT NULL,
    USER_ID         VARCHAR2(50)    NOT NULL,
    VIEW_DATE       DATE            NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_NOTICE_VIEW_LOG PRIMARY KEY (NOTICE_ID, USER_ID, VIEW_DATE)
);
COMMENT ON TABLE  TB_NOTICE_VIEW_LOG           IS '공지 조회 로그 (사용자·일자별 1건 - 중복 조회 판정)';
COMMENT ON COLUMN TB_NOTICE_VIEW_LOG.VIEW_DATE IS '조회일자';

-- ---------------------------------------------------------------------
-- 메일 템플릿 (언어별) : 머리글 / 안내 문구 / 바닥글은 수신자 언어로
--  - 새 언어 추가 = LANG 코드 + 이 테이블에 템플릿 등록 (코드 수정 없음)
--  - 치환자: {{title}} {{postDate}} {{link}} {{categoryNm}}
-- ---------------------------------------------------------------------
CREATE TABLE TB_MAIL_TEMPLATE (
    TEMPLATE_CD     VARCHAR2(50)    NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    SUBJECT         VARCHAR2(500)   NOT NULL,
    HEADER_HTML     VARCHAR2(4000),
    GUIDE_HTML      VARCHAR2(4000),
    FOOTER_HTML     VARCHAR2(4000),
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_MAIL_TEMPLATE PRIMARY KEY (TEMPLATE_CD, LANG_CD)
);
COMMENT ON TABLE  TB_MAIL_TEMPLATE             IS '메일 템플릿 (언어별)';
COMMENT ON COLUMN TB_MAIL_TEMPLATE.TEMPLATE_CD IS '템플릿코드 (예: NOTICE)';
COMMENT ON COLUMN TB_MAIL_TEMPLATE.LANG_CD     IS '언어 (공통코드 LANG)';
COMMENT ON COLUMN TB_MAIL_TEMPLATE.SUBJECT     IS '메일 제목 (치환자 사용 가능)';
COMMENT ON COLUMN TB_MAIL_TEMPLATE.HEADER_HTML IS '머리글';
COMMENT ON COLUMN TB_MAIL_TEMPLATE.GUIDE_HTML  IS '안내 문구';
COMMENT ON COLUMN TB_MAIL_TEMPLATE.FOOTER_HTML IS '바닥글';
