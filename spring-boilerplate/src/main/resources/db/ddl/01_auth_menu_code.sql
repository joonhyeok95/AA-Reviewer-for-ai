CREATE SEQUENCE SQ_MENU START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_MENU (
    MENU_ID         NUMBER(19)      NOT NULL,
    PARENT_MENU_ID  NUMBER(19),
    MODULE_CD       VARCHAR2(50),
    VIEW_TYPE_CD    VARCHAR2(50)    NOT NULL,
    MENU_URL        VARCHAR2(1000),
    PERM_CD         VARCHAR2(100),
    NEW_WINDOW_YN   VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    SORT_ORDER      NUMBER(5)       DEFAULT 0   NOT NULL,
    ADMIN_MENU_YN   VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    SIDE_MENU_YN    VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    DISPLAY_YN      VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_MENU PRIMARY KEY (MENU_ID),
    CONSTRAINT FK_MENU_01 FOREIGN KEY (PARENT_MENU_ID) REFERENCES TB_MENU (MENU_ID)
);
COMMENT ON TABLE  TB_MENU                IS '메뉴 (계층형, 깊이 제한 없음)';
COMMENT ON COLUMN TB_MENU.MENU_ID        IS '메뉴ID (SQ_MENU)';
COMMENT ON COLUMN TB_MENU.PARENT_MENU_ID IS '상위메뉴ID (최상위는 NULL)';
COMMENT ON COLUMN TB_MENU.MODULE_CD      IS '모듈코드 (공통코드 MODULE / 공통 메뉴는 NULL)';
COMMENT ON COLUMN TB_MENU.VIEW_TYPE_CD   IS '조회유형 (공통코드 MENU_VIEW_TYPE: MENU, LINK, CONTENT, IFRAME)';
COMMENT ON COLUMN TB_MENU.MENU_URL       IS 'URL (MENU: 화면경로, LINK/IFRAME: 대상 URL, CONTENT: NULL)';
COMMENT ON COLUMN TB_MENU.PERM_CD        IS 'API 권한 리소스코드 (예: sample → sample.list/add/edit/del). TB_ROLE_MENU 의 LIST/ADD/EDIT/DEL 이 API 권한이 된다';
COMMENT ON COLUMN TB_MENU.NEW_WINDOW_YN  IS '새창여부 (LINK 유형)';
COMMENT ON COLUMN TB_MENU.SORT_ORDER     IS '정렬순서 (같은 상위메뉴 내)';
COMMENT ON COLUMN TB_MENU.ADMIN_MENU_YN  IS '관리자메뉴여부 (Y: 상위메뉴 하위에 붙는 관리자 전용 관리메뉴)';
COMMENT ON COLUMN TB_MENU.SIDE_MENU_YN   IS '사이드메뉴여부 (Y: 사이트 상단 유틸리티 영역에 출력)';
COMMENT ON COLUMN TB_MENU.DISPLAY_YN     IS '노출여부 (N: 메뉴 트리에 표시하지 않음, 권한 체크 대상으로만 사용 - 상세/등록 화면 등)';
COMMENT ON COLUMN TB_MENU.USE_YN         IS '사용여부';
CREATE INDEX IX_MENU_01 ON TB_MENU (PARENT_MENU_ID, SORT_ORDER);

CREATE TABLE TB_MENU_LANG (
    MENU_ID         NUMBER(19)      NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    MENU_NM         VARCHAR2(200)   NOT NULL,
    MENU_CONTENT    CLOB,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_MENU_LANG PRIMARY KEY (MENU_ID, LANG_CD),
    CONSTRAINT FK_MENU_LANG_01 FOREIGN KEY (MENU_ID) REFERENCES TB_MENU (MENU_ID)
);
COMMENT ON TABLE  TB_MENU_LANG              IS '메뉴 다국어';
COMMENT ON COLUMN TB_MENU_LANG.MENU_NM      IS '메뉴명';
COMMENT ON COLUMN TB_MENU_LANG.MENU_CONTENT IS '본문 (조회유형 CONTENT 인 경우 HTML)';

CREATE TABLE TB_ROLE_MENU (
    ROLE_ID         NUMBER(19)      NOT NULL,
    MENU_ID         NUMBER(19)      NOT NULL,
    LIST_YN         VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    ADD_YN          VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    EDIT_YN         VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    DEL_YN          VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_ROLE_MENU PRIMARY KEY (ROLE_ID, MENU_ID),
    CONSTRAINT FK_ROLE_MENU_01 FOREIGN KEY (ROLE_ID) REFERENCES TB_ROLE (ROLE_ID),
    CONSTRAINT FK_ROLE_MENU_02 FOREIGN KEY (MENU_ID) REFERENCES TB_MENU (MENU_ID)
);
COMMENT ON TABLE  TB_ROLE_MENU         IS '권한별 메뉴 접근 (Keycloak scope 와 동일 체계: list/add/edit/del)';
COMMENT ON COLUMN TB_ROLE_MENU.LIST_YN IS '조회권한 (*.list)';
COMMENT ON COLUMN TB_ROLE_MENU.ADD_YN  IS '등록권한 (*.add)';
COMMENT ON COLUMN TB_ROLE_MENU.EDIT_YN IS '수정권한 (*.edit)';
COMMENT ON COLUMN TB_ROLE_MENU.DEL_YN  IS '삭제권한 (*.del)';
CREATE INDEX IX_ROLE_MENU_01 ON TB_ROLE_MENU (MENU_ID);
