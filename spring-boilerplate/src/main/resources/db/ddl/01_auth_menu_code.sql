-- =====================================================================
-- 01. 공통코드 / 사용자·부서 / 권한 / 메뉴  (Oracle)
--  - 설계 문서 : docs/design/01_auth_menu_code.md
--  - local(H2 Oracle 모드)에서는 기동 시 이 스크립트로 스키마를 생성한다. (dev/prod 는 DBA 적용)
--  - 공통 컬럼 : CREATED_BY, CREATED_AT, UPDATED_BY, UPDATED_AT
--  - 여부 컬럼 : VARCHAR2(1) 'Y'/'N'
--  - 공통코드 참조 컬럼(*_CD)은 DB FK 를 걸지 않고 애플리케이션에서 검증한다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 공통코드
-- ---------------------------------------------------------------------
CREATE TABLE TB_CODE_GROUP (
    GROUP_CD        VARCHAR2(50)    NOT NULL,
    GROUP_DESC      VARCHAR2(1000),
    SORT_ORDER      NUMBER(5)       DEFAULT 0   NOT NULL,
    SYSTEM_YN       VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_CODE_GROUP PRIMARY KEY (GROUP_CD)
);
COMMENT ON TABLE  TB_CODE_GROUP            IS '공통코드 그룹';
COMMENT ON COLUMN TB_CODE_GROUP.GROUP_CD   IS '그룹코드 (예: MENU_VIEW_TYPE)';
COMMENT ON COLUMN TB_CODE_GROUP.GROUP_DESC IS '설명 (관리용)';
COMMENT ON COLUMN TB_CODE_GROUP.SORT_ORDER IS '정렬순서';
COMMENT ON COLUMN TB_CODE_GROUP.SYSTEM_YN  IS '시스템코드여부 (Y: 화면에서 삭제/코드변경 불가)';
COMMENT ON COLUMN TB_CODE_GROUP.USE_YN     IS '사용여부';

CREATE TABLE TB_CODE_GROUP_LANG (
    GROUP_CD        VARCHAR2(50)    NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    GROUP_NM        VARCHAR2(200)   NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_CODE_GROUP_LANG PRIMARY KEY (GROUP_CD, LANG_CD),
    CONSTRAINT FK_CODE_GROUP_LANG_01 FOREIGN KEY (GROUP_CD) REFERENCES TB_CODE_GROUP (GROUP_CD)
);
COMMENT ON TABLE  TB_CODE_GROUP_LANG          IS '공통코드 그룹 다국어';
COMMENT ON COLUMN TB_CODE_GROUP_LANG.LANG_CD  IS '언어코드 (공통코드 LANG: ko, en)';
COMMENT ON COLUMN TB_CODE_GROUP_LANG.GROUP_NM IS '그룹명';

CREATE TABLE TB_CODE (
    GROUP_CD        VARCHAR2(50)    NOT NULL,
    CODE            VARCHAR2(50)    NOT NULL,
    CODE_DESC       VARCHAR2(1000),
    SORT_ORDER      NUMBER(5)       DEFAULT 0   NOT NULL,
    ATTR1           VARCHAR2(200),
    ATTR2           VARCHAR2(200),
    ATTR3           VARCHAR2(200),
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_CODE PRIMARY KEY (GROUP_CD, CODE),
    CONSTRAINT FK_CODE_01 FOREIGN KEY (GROUP_CD) REFERENCES TB_CODE_GROUP (GROUP_CD)
);
COMMENT ON TABLE  TB_CODE            IS '공통코드';
COMMENT ON COLUMN TB_CODE.CODE       IS '코드';
COMMENT ON COLUMN TB_CODE.CODE_DESC  IS '설명 (관리용)';
COMMENT ON COLUMN TB_CODE.ATTR1      IS '확장속성1 (코드별 부가값, 예: 아이콘/색상/매핑값)';
COMMENT ON COLUMN TB_CODE.ATTR2      IS '확장속성2';
COMMENT ON COLUMN TB_CODE.ATTR3      IS '확장속성3';

CREATE TABLE TB_CODE_LANG (
    GROUP_CD        VARCHAR2(50)    NOT NULL,
    CODE            VARCHAR2(50)    NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    CODE_NM         VARCHAR2(200)   NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_CODE_LANG PRIMARY KEY (GROUP_CD, CODE, LANG_CD),
    CONSTRAINT FK_CODE_LANG_01 FOREIGN KEY (GROUP_CD, CODE) REFERENCES TB_CODE (GROUP_CD, CODE)
);
COMMENT ON TABLE  TB_CODE_LANG         IS '공통코드 다국어';
COMMENT ON COLUMN TB_CODE_LANG.CODE_NM IS '코드명';

-- ---------------------------------------------------------------------
-- 2. 인사 마스터 : 사업장 / 부서 / 사용자  (인사 시스템 연동 대상)
--  - 공지 등 업무 테이블에는 사업장코드/부서코드만 저장하고 명칭은 조회 시점에 이 테이블에서 가져온다.
--  - 국문명 + 영문명 제공 (영문 이외 언어는 영문명 → 국문명 순으로 대체)
-- ---------------------------------------------------------------------
CREATE TABLE TB_WORKPLACE (
    WORKPLACE_CD    VARCHAR2(50)    NOT NULL,
    WORKPLACE_NM    VARCHAR2(200)   NOT NULL,
    WORKPLACE_NM_EN VARCHAR2(200),
    SORT_ORDER      NUMBER(5)       DEFAULT 0   NOT NULL,
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_WORKPLACE PRIMARY KEY (WORKPLACE_CD)
);
COMMENT ON TABLE  TB_WORKPLACE                 IS '사업장 (인사 마스터)';
COMMENT ON COLUMN TB_WORKPLACE.WORKPLACE_NM    IS '사업장명 (국문)';
COMMENT ON COLUMN TB_WORKPLACE.WORKPLACE_NM_EN IS '사업장명 (영문)';

CREATE TABLE TB_USER (
    USER_ID         VARCHAR2(50)    NOT NULL,
    IDP_SUBJECT     VARCHAR2(64),
    USER_NM         VARCHAR2(100)   NOT NULL,
    EMAIL           VARCHAR2(200),
    USER_TYPE_CD    VARCHAR2(50)    NOT NULL,
    COMPANY_NM      VARCHAR2(200),
    LANG_CD         VARCHAR2(10),
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_USER PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USER_01 UNIQUE (IDP_SUBJECT)
);
COMMENT ON TABLE  TB_USER              IS '사용자';
COMMENT ON COLUMN TB_USER.USER_ID      IS '사용자ID (로그인ID = Keycloak username, 화면 표시/감사용)';
COMMENT ON COLUMN TB_USER.IDP_SUBJECT  IS 'IdP 사용자 고유ID (Keycloak user id = 토큰 sub). 권한 매핑 기준 - 변경 불가 값';
COMMENT ON COLUMN TB_USER.USER_NM      IS '사용자명';
COMMENT ON COLUMN TB_USER.USER_TYPE_CD IS '사용자유형 (공통코드 USER_TYPE: EMP, SAIT_GPA, AFFILIATE, PARTNER, NON_REAL)';
COMMENT ON COLUMN TB_USER.COMPANY_NM   IS '소속회사명 (관계사/협력사)';
COMMENT ON COLUMN TB_USER.LANG_CD      IS '사용자 설정 언어 (공통코드 LANG, NULL 이면 기본 언어)';

CREATE TABLE TB_DEPT (
    DEPT_CD         VARCHAR2(50)    NOT NULL,
    DEPT_NM         VARCHAR2(200)   NOT NULL,
    DEPT_NM_EN      VARCHAR2(200),
    WORKPLACE_CD    VARCHAR2(50),
    PARENT_DEPT_CD  VARCHAR2(50),
    SORT_ORDER      NUMBER(5)       DEFAULT 0   NOT NULL,
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_DEPT PRIMARY KEY (DEPT_CD),
    CONSTRAINT FK_DEPT_01 FOREIGN KEY (PARENT_DEPT_CD) REFERENCES TB_DEPT (DEPT_CD),
    CONSTRAINT FK_DEPT_02 FOREIGN KEY (WORKPLACE_CD) REFERENCES TB_WORKPLACE (WORKPLACE_CD)
);
COMMENT ON TABLE  TB_DEPT                IS '부서 (인사 마스터 조직도)';
COMMENT ON COLUMN TB_DEPT.DEPT_NM        IS '부서명 (국문)';
COMMENT ON COLUMN TB_DEPT.DEPT_NM_EN     IS '부서명 (영문)';
COMMENT ON COLUMN TB_DEPT.WORKPLACE_CD   IS '사업장코드 (TB_WORKPLACE)';
COMMENT ON COLUMN TB_DEPT.PARENT_DEPT_CD IS '상위부서코드';

CREATE TABLE TB_USER_DEPT (
    USER_ID         VARCHAR2(50)    NOT NULL,
    DEPT_CD         VARCHAR2(50)    NOT NULL,
    MAIN_DEPT_YN    VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_USER_DEPT PRIMARY KEY (USER_ID, DEPT_CD),
    CONSTRAINT FK_USER_DEPT_01 FOREIGN KEY (USER_ID) REFERENCES TB_USER (USER_ID),
    CONSTRAINT FK_USER_DEPT_02 FOREIGN KEY (DEPT_CD) REFERENCES TB_DEPT (DEPT_CD)
);
COMMENT ON TABLE  TB_USER_DEPT              IS '사용자 소속부서 (N개, 겸직 포함)';
COMMENT ON COLUMN TB_USER_DEPT.MAIN_DEPT_YN IS '주부서여부';
CREATE INDEX IX_USER_DEPT_01 ON TB_USER_DEPT (DEPT_CD);
CREATE INDEX IX_DEPT_01 ON TB_DEPT (WORKPLACE_CD);
CREATE INDEX IX_DEPT_02 ON TB_DEPT (PARENT_DEPT_CD);

-- ---------------------------------------------------------------------
-- 3. 권한
-- ---------------------------------------------------------------------
CREATE SEQUENCE SQ_ROLE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_ROLE (
    ROLE_ID         NUMBER(19)      NOT NULL,
    ROLE_CD         VARCHAR2(50)    NOT NULL,
    ROLE_TYPE_CD    VARCHAR2(50)    NOT NULL,
    ROLE_LEVEL      NUMBER(2)       NOT NULL,
    MODULE_CD       VARCHAR2(50),
    ROLE_DESC       VARCHAR2(1000),
    SORT_ORDER      NUMBER(5)       DEFAULT 0   NOT NULL,
    SYSTEM_YN       VARCHAR2(1)     DEFAULT 'N' NOT NULL,
    USE_YN          VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_ROLE PRIMARY KEY (ROLE_ID),
    CONSTRAINT UK_ROLE_01 UNIQUE (ROLE_CD)
);
COMMENT ON TABLE  TB_ROLE              IS '권한';
COMMENT ON COLUMN TB_ROLE.ROLE_ID      IS '권한ID (SQ_ROLE)';
COMMENT ON COLUMN TB_ROLE.ROLE_CD      IS '권한코드 (예: SYS_ADMIN, TX_MASTER, TX_MANAGER, TX_MANAGER_READ)';
COMMENT ON COLUMN TB_ROLE.ROLE_TYPE_CD IS '권한유형 (공통코드 ROLE_TYPE: SYSTEM_ADMIN, MODULE_MASTER, MODULE_MANAGER, GENERAL_USER)';
COMMENT ON COLUMN TB_ROLE.ROLE_LEVEL   IS '권한레벨 (1:시스템관리자 2:모듈마스터 3:모듈매니저 4:일반사용자, 작을수록 상위)';
COMMENT ON COLUMN TB_ROLE.MODULE_CD    IS '모듈코드 (공통코드 MODULE: TX, WS / 모듈 무관 권한은 NULL)';
COMMENT ON COLUMN TB_ROLE.SYSTEM_YN    IS '기본권한여부 (Y: 삭제/코드변경 불가)';
CREATE INDEX IX_ROLE_01 ON TB_ROLE (MODULE_CD, ROLE_LEVEL);

CREATE TABLE TB_ROLE_LANG (
    ROLE_ID         NUMBER(19)      NOT NULL,
    LANG_CD         VARCHAR2(10)    NOT NULL,
    ROLE_NM         VARCHAR2(200)   NOT NULL,
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_ROLE_LANG PRIMARY KEY (ROLE_ID, LANG_CD),
    CONSTRAINT FK_ROLE_LANG_01 FOREIGN KEY (ROLE_ID) REFERENCES TB_ROLE (ROLE_ID)
);
COMMENT ON TABLE  TB_ROLE_LANG         IS '권한 다국어';
COMMENT ON COLUMN TB_ROLE_LANG.ROLE_NM IS '권한명';

CREATE SEQUENCE SQ_USER_ROLE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_USER_ROLE (
    USER_ROLE_ID    NUMBER(19)      NOT NULL,
    USER_ID         VARCHAR2(50)    NOT NULL,
    ROLE_ID         NUMBER(19)      NOT NULL,
    START_DT        DATE            NOT NULL,
    END_DT          DATE            DEFAULT DATE '9999-12-31' NOT NULL,
    GRANT_REASON    VARCHAR2(1000),
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_USER_ROLE PRIMARY KEY (USER_ROLE_ID),
    CONSTRAINT FK_USER_ROLE_01 FOREIGN KEY (USER_ID) REFERENCES TB_USER (USER_ID),
    CONSTRAINT FK_USER_ROLE_02 FOREIGN KEY (ROLE_ID) REFERENCES TB_ROLE (ROLE_ID),
    CONSTRAINT CK_USER_ROLE_01 CHECK (START_DT <= END_DT)
);
COMMENT ON TABLE  TB_USER_ROLE              IS '사용자별 권한 부여';
COMMENT ON COLUMN TB_USER_ROLE.USER_ROLE_ID IS '사용자권한ID (SQ_USER_ROLE)';
COMMENT ON COLUMN TB_USER_ROLE.START_DT     IS '권한시작일';
COMMENT ON COLUMN TB_USER_ROLE.END_DT       IS '권한종료일 (무기한: 9999-12-31)';
COMMENT ON COLUMN TB_USER_ROLE.GRANT_REASON IS '부여사유';
CREATE INDEX IX_USER_ROLE_01 ON TB_USER_ROLE (USER_ID, END_DT, START_DT);
CREATE INDEX IX_USER_ROLE_02 ON TB_USER_ROLE (ROLE_ID);

CREATE SEQUENCE SQ_DEPT_ROLE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_DEPT_ROLE (
    DEPT_ROLE_ID    NUMBER(19)      NOT NULL,
    DEPT_CD         VARCHAR2(50)    NOT NULL,
    ROLE_ID         NUMBER(19)      NOT NULL,
    START_DT        DATE            NOT NULL,
    END_DT          DATE            DEFAULT DATE '9999-12-31' NOT NULL,
    GRANT_REASON    VARCHAR2(1000),
    CREATED_BY      VARCHAR2(50)    NOT NULL,
    CREATED_AT      TIMESTAMP(6)    NOT NULL,
    UPDATED_BY      VARCHAR2(50)    NOT NULL,
    UPDATED_AT      TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_DEPT_ROLE PRIMARY KEY (DEPT_ROLE_ID),
    CONSTRAINT FK_DEPT_ROLE_01 FOREIGN KEY (DEPT_CD) REFERENCES TB_DEPT (DEPT_CD),
    CONSTRAINT FK_DEPT_ROLE_02 FOREIGN KEY (ROLE_ID) REFERENCES TB_ROLE (ROLE_ID),
    CONSTRAINT CK_DEPT_ROLE_01 CHECK (START_DT <= END_DT)
);
COMMENT ON TABLE  TB_DEPT_ROLE              IS '부서(그룹)별 권한 부여 - 소속 사용자 전원에게 적용';
COMMENT ON COLUMN TB_DEPT_ROLE.DEPT_ROLE_ID IS '부서권한ID (SQ_DEPT_ROLE)';
COMMENT ON COLUMN TB_DEPT_ROLE.START_DT     IS '권한시작일';
COMMENT ON COLUMN TB_DEPT_ROLE.END_DT       IS '권한종료일 (무기한: 9999-12-31)';
CREATE INDEX IX_DEPT_ROLE_01 ON TB_DEPT_ROLE (DEPT_CD, END_DT, START_DT);
CREATE INDEX IX_DEPT_ROLE_02 ON TB_DEPT_ROLE (ROLE_ID);

