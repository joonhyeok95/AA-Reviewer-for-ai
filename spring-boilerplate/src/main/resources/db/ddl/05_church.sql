CREATE TABLE TB_CATECHISM (
    CATECHISM_ID        NUMBER(19)      NOT NULL,
    CATECHISM_CD        VARCHAR2(30 CHAR)    NOT NULL,
    TITLE               VARCHAR2(200 CHAR)   NOT NULL,
    DESCRIPTION         VARCHAR2(1000 CHAR),
    SORT_ORDER          NUMBER(5)       DEFAULT 0 NOT NULL,
    USE_YN              VARCHAR2(1 CHAR)     DEFAULT 'Y' NOT NULL,
    CREATED_BY          VARCHAR2(50 CHAR)    NOT NULL,
    CREATED_AT          TIMESTAMP(6)    NOT NULL,
    UPDATED_BY          VARCHAR2(50 CHAR)    NOT NULL,
    UPDATED_AT          TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_CATECHISM PRIMARY KEY (CATECHISM_ID),
    CONSTRAINT UK_CATECHISM_01 UNIQUE (CATECHISM_CD)
);
CREATE SEQUENCE SQ_CATECHISM START WITH 1 INCREMENT BY 1 NOCACHE;
COMMENT ON TABLE  TB_CATECHISM              IS '교리문답 (하이델베르크, 웨스트민스터 소요리 등)';
COMMENT ON COLUMN TB_CATECHISM.CATECHISM_ID IS '교리문답 ID (SQ_CATECHISM)';
COMMENT ON COLUMN TB_CATECHISM.CATECHISM_CD IS '교리문답 코드 (예: HEIDELBERG)';
COMMENT ON COLUMN TB_CATECHISM.TITLE        IS '이름';
COMMENT ON COLUMN TB_CATECHISM.DESCRIPTION  IS '설명';
COMMENT ON COLUMN TB_CATECHISM.SORT_ORDER   IS '정렬순서';
COMMENT ON COLUMN TB_CATECHISM.USE_YN       IS '사용여부';

CREATE TABLE TB_CATECHISM_UNIT (
    UNIT_ID             NUMBER(19)      NOT NULL,
    CATECHISM_ID        NUMBER(19)      NOT NULL,
    PARENT_UNIT_ID      NUMBER(19),
    UNIT_TYPE_CD        VARCHAR2(30 CHAR)    NOT NULL,
    UNIT_NO             NUMBER(5),
    TITLE               VARCHAR2(200 CHAR),
    SORT_ORDER          NUMBER(5)       DEFAULT 0 NOT NULL,
    CREATED_BY          VARCHAR2(50 CHAR)    NOT NULL,
    CREATED_AT          TIMESTAMP(6)    NOT NULL,
    UPDATED_BY          VARCHAR2(50 CHAR)    NOT NULL,
    UPDATED_AT          TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_CATECHISM_UNIT PRIMARY KEY (UNIT_ID),
    CONSTRAINT FK_CATECHISM_UNIT_01 FOREIGN KEY (CATECHISM_ID) REFERENCES TB_CATECHISM (CATECHISM_ID),
    CONSTRAINT FK_CATECHISM_UNIT_02 FOREIGN KEY (PARENT_UNIT_ID) REFERENCES TB_CATECHISM_UNIT (UNIT_ID)
);
CREATE INDEX IX_CATECHISM_UNIT_01 ON TB_CATECHISM_UNIT (CATECHISM_ID, PARENT_UNIT_ID, SORT_ORDER);
CREATE SEQUENCE SQ_CATECHISM_UNIT START WITH 1 INCREMENT BY 1 NOCACHE;
COMMENT ON TABLE  TB_CATECHISM_UNIT                IS '교리문답 단위 트리 (부 → 주일, 장 등)';
COMMENT ON COLUMN TB_CATECHISM_UNIT.UNIT_ID        IS '단위 ID (SQ_CATECHISM_UNIT)';
COMMENT ON COLUMN TB_CATECHISM_UNIT.CATECHISM_ID   IS '교리문답 ID';
COMMENT ON COLUMN TB_CATECHISM_UNIT.PARENT_UNIT_ID IS '상위 단위 ID (최상위 NULL)';
COMMENT ON COLUMN TB_CATECHISM_UNIT.UNIT_TYPE_CD   IS '단위 유형 (공통코드 CATECHISM_UNIT_TYPE : PART 부, LORDS_DAY 주일, CHAPTER 장)';
COMMENT ON COLUMN TB_CATECHISM_UNIT.UNIT_NO        IS '번호 (제45주일 → 45)';
COMMENT ON COLUMN TB_CATECHISM_UNIT.TITLE          IS '제목 (예: 감사에 관하여)';
COMMENT ON COLUMN TB_CATECHISM_UNIT.SORT_ORDER     IS '같은 상위 안의 정렬순서';

