-- =====================================================================
-- 교회 주보 / 교리문답 / 전례문 - Oracle
--
--  [주보]  TB_BULLETIN (1주 1건)
--            ├ TB_BULLETIN_ORDER      예배순서 n건 (항목, 담당·내용)
--            ├ TB_BULLETIN_NEWS       교회소식 트리 (섹션 → 항목 → 하위 항목, PARENT_NEWS_ID)
--            ├ TB_BULLETIN_DUTY       섬김위원 (역할 × 날짜 = 담당자)
--            ├ TB_BULLETIN_CATECHISM  이번 주 교리문답 단위 n건 (→ TB_CATECHISM_UNIT)
--            └ TB_BULLETIN_TEXT       이번 주 전례문 n건 (→ TB_LITURGY_TEXT, 사도신경·주기도문 등)
--
--  [교리문답] 여러 교리문답(하이델베르크, 웨스트민스터 소요리 …)을 같은 구조로
--          TB_CATECHISM                 교리문답
--            └ TB_CATECHISM_UNIT        단위 트리 (부 → 주일 / 장 …, PARENT_UNIT_ID, 유형 공통코드)
--                └ TB_CATECHISM_QA      문답 (문 번호·질문)
--                    └ TB_CATECHISM_ANSWER  답 단락 (첫째·둘째 …)
--                        └ TB_CATECHISM_PROOF  근거 성구
--
--  [전례문] 사도신경·주기도문·교독문 등 매주 재사용하는 본문
--          TB_LITURGY_TEXT → TB_LITURGY_LINE (줄마다 화자 : 인도자/성도/다함께)
--
--  - 하위 행은 대리키(시퀀스) + 정렬순서. 저장은 부모 단위로 하위 전체를 교체한다.
--  - 유형·화자·상태는 공통코드 (BULLETIN_STATUS, CATECHISM_UNIT_TYPE, LITURGY_TYPE, LITURGY_SPEAKER)
-- =====================================================================

-- ---------------------------------------------------------------------
-- 교리문답
